import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import { readJsonl, invariantInputHash, validateCorpus } from './corpus-integrity.mjs';
const require = createRequire(import.meta.url);
const { renderRequest } = require('../../../dist/src/r7/jev/render.js');
const directory = process.argv[2];
assert.ok(directory, 'supply actual corpus directory');
const rows = readJsonl(resolve(directory, 'cases.jsonl'));
const episodes = readJsonl(resolve(directory, 'episodes.jsonl'));
let passed = 0;
assert.deepEqual(validateCorpus(rows, episodes).counts, { train: 64, dev: 16, test: 16 }); passed++;
const shuffled = structuredClone(rows[0].request);
shuffled.candidates.reverse();
assert.equal(invariantInputHash(shuffled), invariantInputHash(rows[0].request));
assert.notEqual(renderRequest(shuffled).text, rows[0].rendered.text); passed++;
const idsChanged = structuredClone(rows[0].request);
idsChanged.requestId = 'new-request-id';
idsChanged.candidates.forEach((candidate, index) => { candidate.id = `new-${index}`; });
assert.equal(renderRequest(idsChanged).text, rows[0].rendered.text); passed++;
const leaked = structuredClone(rows);
leaked[1].split = 'test';
assert.throws(() => validateCorpus(leaked, episodes), /split leak|episode identity/); passed++;
const forged = structuredClone(rows);
forged[0].execution.committedReceipts[0].payload = { invented: true };
assert.throws(() => validateCorpus(forged, episodes), /uncommitted receipt/); passed++;
const altered = structuredClone(rows);
altered[0].rendered.text += '\nLABEL:chosen';
assert.throws(() => validateCorpus(altered, episodes), /rendered input mismatch/); passed++;
const promoted = structuredClone(rows);
promoted[0].researchTrainReady = true;
assert.throws(() => validateCorpus(promoted, episodes), /misclassified evidence/); passed++;
console.log(JSON.stringify({ ok: true, passed, data: directory, modelCalls: 0,
  note: 'Integrity negative controls use copies of actual captured cases; no training evidence is fabricated.' }));
